

-- A foreign key create relation between 2 tables

-- custemers is parent table
-- orders is child table


-- one customer ke pass multiple orders ho sakte hai 
--but ek order ke liye sirf ek customer ho sakta hai


CREATE TABLE IF NOT EXISTS store.orders(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER REFERENCES store.customers(id),
    order_status TEXT
);