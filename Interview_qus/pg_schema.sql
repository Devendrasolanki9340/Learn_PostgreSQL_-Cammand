CREATE SCHEMA IF NOT EXISTS sql_interview_100;
SET search_path TO sql_interview_100, public;





CREATE TABLE sql_interview_100.departments (
 department_id INT PRIMARY KEY,
 department_name VARCHAR(60) NOT NULL UNIQUE
);


CREATE TABLE sql_interview_100.employees (
 employee_id INT PRIMARY KEY,
 employee_name VARCHAR(80) NOT NULL,
 department_id INT NOT NULL REFERENCES sql_interview_100.departments(department_id),
 manager_id INT NULL REFERENCES sql_interview_100.employees(employee_id),
 salary NUMERIC(12,2) NOT NULL CHECK (salary > 0),
 hired_on DATE NOT NULL
);


CREATE TABLE sql_interview_100.customers (
 customer_id INT PRIMARY KEY,
 full_name VARCHAR(80) NOT NULL,
 email VARCHAR(120) NOT NULL UNIQUE,
 city VARCHAR(60) NOT NULL,
 phone VARCHAR(20) NULL,
 referred_by INT NULL REFERENCES sql_interview_100.customers(customer_id),
 registered_at TIMESTAMP NOT NULL
);



CREATE TABLE sql_interview_100.categories (
 category_id INT PRIMARY KEY,
 category_name VARCHAR(60) NOT NULL UNIQUE
);


CREATE TABLE sql_interview_100.products (
 product_id INT PRIMARY KEY,
 category_id INT NOT NULL REFERENCES sql_interview_100.categories(category_id),
 product_name VARCHAR(100) NOT NULL,
 price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
 stock_quantity INT NOT NULL CHECK (stock_quantity >= 0),
 is_active SMALLINT NOT NULL CHECK (is_active IN (0,1))
);


CREATE TABLE sql_interview_100.orders (
 order_id INT PRIMARY KEY,
 customer_id INT NOT NULL REFERENCES sql_interview_100.customers(customer_id),
 employee_id INT NULL REFERENCES sql_interview_100.employees(employee_id),
 ordered_at TIMESTAMP NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('placed','shipped','delivered','cancelled')),
 shipping_fee NUMERIC(12,2) NOT NULL CHECK (shipping_fee >= 0),
 shipped_at TIMESTAMP NULL,
 delivered_at TIMESTAMP NULL,
 CHECK (shipped_at IS NULL OR shipped_at >= ordered_at),
 CHECK (delivered_at IS NULL OR (shipped_at IS NOT NULL AND delivered_at >= shipped_at))
);


CREATE TABLE sql_interview_100.order_items (
 order_item_id INT PRIMARY KEY,
 order_id INT NOT NULL REFERENCES sql_interview_100.orders(order_id),
 product_id INT NOT NULL REFERENCES sql_interview_100.products(product_id),
 quantity INT NOT NULL CHECK (quantity > 0),
 unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
 discount_amount NUMERIC(12,2) NOT NULL CHECK (discount_amount >= 0),
 UNIQUE (order_id, product_id),
 CHECK (discount_amount <= quantity * unit_price)
);


CREATE TABLE sql_interview_100.payments (
 payment_id INT PRIMARY KEY,
 order_id INT NOT NULL REFERENCES sql_interview_100.orders(order_id),
 paid_at TIMESTAMP NOT NULL,
 amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
 method VARCHAR(20) NOT NULL CHECK (method IN ('upi','card','net_banking')),
 status VARCHAR(20) NOT NULL CHECK (status IN ('success','failed'))
);


CREATE TABLE sql_interview_100.order_returns (
 return_id INT PRIMARY KEY,
 order_item_id INT NOT NULL REFERENCES sql_interview_100.order_items(order_item_id),
 returned_at TIMESTAMP NOT NULL,
 quantity INT NOT NULL CHECK (quantity > 0),
 refund_amount NUMERIC(12,2) NOT NULL CHECK (refund_amount >= 0),
 status VARCHAR(20) NOT NULL CHECK (status IN ('requested','approved','rejected'))
);


CREATE TABLE sql_interview_100.reviews (
 review_id INT PRIMARY KEY,
 customer_id INT NOT NULL REFERENCES sql_interview_100.customers(customer_id),
 product_id INT NOT NULL REFERENCES sql_interview_100.products(product_id),
 rating INT NOT NULL CHECK (rating BETWEEN 1 AND 5),
 review_text VARCHAR(300) NULL,
 reviewed_at TIMESTAMP NOT NULL,
 UNIQUE (customer_id, product_id)
);


CREATE TABLE sql_interview_100.wishlist (
 customer_id INT NOT NULL REFERENCES sql_interview_100.customers(customer_id),
 product_id INT NOT NULL REFERENCES sql_interview_100.products(product_id),
 added_at TIMESTAMP NOT NULL,
 PRIMARY KEY (customer_id, product_id)
);


